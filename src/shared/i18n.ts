import type { LanguageSetting } from './types';

export type ResolvedLocale = 'en' | 'zh_CN' | 'ar' | 'fr' | 'ru' | 'es';

export function isRtlLocale(locale: ResolvedLocale): boolean {
  return locale === 'ar';
}

export function resolveLocale(setting: LanguageSetting): ResolvedLocale {
  if (
    setting === 'en' ||
    setting === 'zh_CN' ||
    setting === 'ar' ||
    setting === 'fr' ||
    setting === 'ru' ||
    setting === 'es'
  ) {
    return setting;
  }
  const browserLang = (
    (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage?.()) ||
    (typeof navigator !== 'undefined' && navigator.language) ||
    'en'
  ).toLowerCase();

  if (browserLang.startsWith('zh')) return 'zh_CN';
  if (browserLang.startsWith('ar')) return 'ar';
  if (browserLang.startsWith('fr')) return 'fr';
  if (browserLang.startsWith('ru')) return 'ru';
  if (browserLang.startsWith('es')) return 'es';
  return 'en';
}

